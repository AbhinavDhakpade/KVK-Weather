export const getTranslation = (lang, path) => {
  const dict = translations[lang] || translations.en;
  const keys = path.split(".");
  let value = dict;
  for (const k of keys) {
    value = value?.[k];
  }
  if (value === undefined) {
    let fallback = translations.en;
    for (const k of keys) fallback = fallback?.[k];
    return fallback ?? path;
  }
  return value;
};
